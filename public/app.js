function renderTraits() {
  var list = TRAITS;
  var selIdx = -1;
  list.forEach(function (t, i) { if (t.id === state.sel) { selIdx = i; } });
  var insertAfter = selIdx < 0 ? -1 : Math.min(list.length - 1, Math.floor(selIdx / COLS) * COLS + COLS - 1);
  var html = '';
  list.forEach(function (t, i) {
    html += tileHtml(t);
    if (i === insertAfter) { html += detailHtml(list[selIdx]); }
  });
  document.getElementById('traitGrid').innerHTML = html;
}

