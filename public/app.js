function diceWord(n) { return n === 1 ? 'кубик' : 'кубика'; }
function segs(str) {
  var out = [];
  var re = /\[\[(.+?)\]\]/g;
  var last = 0;
  var m;
  while ((m = re.exec(str))) {
    if (m.index > last) { out.push({ isText: true, isChip: false, isTag: false, t: str.slice(last, m.index) }); }
    var k = m[1];
    if (k === 'r' || k === 'b' || k === 'y') {
      out.push({ isText: false, isChip: true, isTag: false, cls: 'ichip chip-' + k });
    } else {
      var p = k.split(':');
      var main = p[0] === 'm';
      out.push({ isText: false, isChip: false, isTag: true, cls: 'itag ' + (main ? 'itag-main' : 'itag-extra'), b: main ? 'bm' : 'bx', t: p[1] });
    }
    last = re.lastIndex;
  }
  if (last < str.length) { out.push({ isText: true, isChip: false, isTag: false, t: str.slice(last) }); }
  return out;
}

function esc(s) {
  return String(s).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
  });
}
function segsHtml(str) {
  return segs(str).map(function (sg) {
    if (sg.isText) { return esc(sg.t); }
    if (sg.isChip) { return '<span class="' + sg.cls + '"></span>'; }
    return '<span class="' + sg.cls + '"><span class="' + sg.b + '"></span>' + esc(sg.t) + '</span>';
  }).join('');
}

